/** Normalisasi minimal: huruf kecil, trim, dan unicode compatibility form. */
export function normalizeWord(value: string): string {
  return value.normalize('NFKC').trim().toLowerCase();
}

/**
 * Exact match hanya. `admin` ditolak, `madmin` / `adminku` tetap boleh.
 */
export function isBlockedWord(value: string): boolean {
  return BLOCKED_WORDS.has(normalizeWord(value));
}
